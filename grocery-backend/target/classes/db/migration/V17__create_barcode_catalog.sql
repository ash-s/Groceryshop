-- V17: built-in barcode catalog — a reference list of common grocery items.
-- This helps a shop set up products quickly and lets a scanned barcode resolve
-- to a name even before the product exists. Barcodes are NOT shipped pre-filled
-- from guesswork: they are attached by scanning the real packet once (scan-to-set),
-- so every stored barcode is guaranteed to match the printed one.

CREATE TABLE barcode_catalog (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(50) NULL,
    name VARCHAR(150) NOT NULL,
    brand VARCHAR(100) NULL,
    category VARCHAR(100) NULL,
    CONSTRAINT uk_barcode_catalog_code UNIQUE (code)
);

